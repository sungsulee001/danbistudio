function assertFile(filePath, label) {
  const stats = statSync(filePath, { throwIfNoEntry: false });
  if (!stats?.isFile()) {
    throw new Error(`Missing required handoff source file: ${label}`);
  }
}

function assertInsideRoot(workspaceRoot, targetPath, label) {
  const relative = path.relative(workspaceRoot, targetPath);
  if (!relative || relative.startsWith('..') || path.isAbsolute(relative)) {
    throw new Error(`${label} must stay inside workspace: ${targetPath}`);
  }
}

function hashFile(filePath) {
  return createHash('sha256').update(readFileSync(filePath)).digest('hex');
}

function toPowerShellSingleQuoted(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function isNonEmptyString(value) {
  return typeof value === 'string' && value.trim().length > 0;
}

function readJson(filePath) {
  return JSON.parse(readFileSync(filePath, 'utf8'));
}

function normalizeSlash(value) {
  return value.replace(/\\/g, '/');
}

function parseCliArgs(argv) {
  const options = {};
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--acceptance-report') {
      options.acceptanceReportPath = readRequiredValue(argv, ++index, arg);
    } else if (arg === '--root-dir') {
      options.rootDir = readRequiredValue(argv, ++index, arg);
    } else if (arg === '--out') {
      options.handoffDir = readRequiredValue(argv, ++index, arg);
    } else if (arg === '--help') {
      options.help = true;
    } else {
      throw new Error(`Unknown option: ${arg}`);
    }
  }
  return options;
}

function readRequiredValue(argv, index, option) {
  const value = argv[index];
  if (typeof value !== 'string' || value.length === 0 || value.startsWith('--')) {
    throw new Error(`${option} requires a value.`);
  }
  return value;
}

function formatHelp() {
  return [
    'Usage: node scripts/electron-release-handoff.mjs [--acceptance-report <path>] [--root-dir <path>] [--out <path>]',
    '',
    'Creates a fresh-Windows release handoff directory with installer artifacts, checksums, evidence reports, and manual acceptance instructions.',
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  let options = {};
  try {
    options = parseCliArgs(process.argv.slice(2));
    if (options.help) {
      console.log(formatHelp());
      process.exit(0);
    }
    const result = buildElectronReleaseHandoff(options);
    console.log(JSON.stringify({
      status: result.manifest.status,
      handoffDir: result.handoffDir,
      fileCount: result.manifest.files.length,
      installer: result.manifest.files.find((file) => file.role === 'installer')?.target,
      checklist: result.manifest.checklist,
      failureCount: 0,
      failures: [],
    }, null, 2));
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    console.log(JSON.stringify({
      status: 'failed',
      handoffDir: typeof options.handoffDir === 'string' ? normalizeSlash(options.handoffDir) : null,
      failureCount: 1,
      failures: [message],
    }, null, 2));
    console.error(message);
    process.exit(1);
  }
}
