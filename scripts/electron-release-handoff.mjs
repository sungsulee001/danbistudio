    '  if ($Current -and $Current.Trim().Length -gt 0) { return $Current.Trim() }',
    '  if ($NoPrompt) { throw "Missing required value: $Prompt" }',
    '  do { $value = Read-Host $Prompt } while (!$value -or $value.Trim().Length -eq 0)',
    '  return $value.Trim()',
    '}',
