    '  $uninstaller = Find-Uninstaller $installDir',
    '  if ($uninstaller) {',
    '    Start-Process -FilePath $uninstaller -ArgumentList @("/S") -Wait -PassThru -WindowStyle Hidden | Out-Null',
    '    $cleanup.uninstallerRan = $true',
    '  }',
    '  Wait-PathGone $installDir 60000',
    '  if ($installRoot -and (Test-Path -LiteralPath $installRoot)) {',
    '    Remove-Item -LiteralPath $installRoot -Recurse -Force -ErrorAction SilentlyContinue',
    '  }',
    '  $cleanup.installDirRemoved = !(Test-Path -LiteralPath $installDir)',
    '  $cleanup.installRootRemoved = !(Test-Path -LiteralPath $installRoot)',
    '  $cleanup.remainingNewShortcuts = Remove-NewShortcuts -Snapshot @($Session.shortcuts.before)',
    '  $cleanup.shortcutCleanup = @($cleanup.remainingNewShortcuts).Count -eq 0',
