    '}',
    'function Wait-PathGone([string]$Path, [int]$TimeoutMs) {',
    '  $deadline = [DateTime]::UtcNow.AddMilliseconds($TimeoutMs)',
    '  while ([DateTime]::UtcNow -lt $deadline) {',
    '    if (!(Test-Path -LiteralPath $Path)) { return }',
    '    Start-Sleep -Milliseconds 500',
    '  }',
    '}',
    'function Remove-NewShortcuts([object[]]$Snapshot) {',
    '  foreach ($item in @($Snapshot)) {',
    '    if (!$item.existed -and (Test-Path -LiteralPath $item.path -PathType Leaf)) {',
    '      Remove-Item -LiteralPath $item.path -Force -ErrorAction SilentlyContinue',
    '    }',
    '  }',
    '  return @($Snapshot | Where-Object { !$_.existed -and (Test-Path -LiteralPath $_.path -PathType Leaf) })',
